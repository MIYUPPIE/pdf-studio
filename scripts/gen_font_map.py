#!/usr/bin/env python3
"""Generate the lazy-loaded fallback font table from MuPDF's font-table.h.

The browser build compiles MuPDF with -DTOFU -DTOFU_CJK (no Noto/CJK fonts in
the wasm). Instead the engine asks the host for a font file the first time a
script needs it. This script derives script -> font-file from MuPDF's own
table so the choice matches native MuPDF exactly.

Outputs:
  services/engine/src/font_map.inc   C++ table rows
  prints the list of font files to copy next to the wasm (one per line) with --list
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MUPDF = os.path.join(ROOT, "third_party", "mupdf")
TABLE = os.path.join(MUPDF, "source", "fitz", "font-table.h")
OUT = os.path.join(ROOT, "services", "engine", "src", "font_map.inc")

DEFNOTO = re.compile(r"^DEFNOTO\((\w+),\s*\"([^\"]*)\",\s*(\w+)\)")
ROW = re.compile(
    r"^(FONT|ALIAS)\((\w+),\s*(\w+),\s*\"([^\"]*)\",\s*(\w+),\s*(\w+),\s*(\w+),\s*([\w|]+)\)")

# Only these forges are lazy-loaded (base14 'urw' stays compiled in).
LAZY_FORGES = {"noto", "sil", "droid"}
# CJK: use Droid Sans Fallback Full (one font for Han/Hangul/Kana) rather than
# the 24 MB Source Han Serif collection.
SKIP_FILES = {"SourceHanSerif-Regular.ttc", "DroidSansFallback.ttf"}


def file_name(forge, name):
    stem, ext = name.rsplit("_", 1)
    return stem.replace("_", "-") + "." + ext


def rows():
    out = []
    for line in open(TABLE, encoding="utf-8"):
        line = line.strip()
        if line.startswith("#define"):
            continue
        m = ROW.match(line)
        d = DEFNOTO.match(line)
        if m:
            _, forge, name, family, script, lang, subfont, attr = m.groups()
        elif d:
            name, family, script = d.groups()
            forge, lang, subfont, attr = "noto", "FZ_LANG_UNSET", "NO_SUBFONT", "REGULAR"
        else:
            continue
        if forge not in LAZY_FORGES:
            continue
        fname = file_name(forge, name)
        if fname in SKIP_FILES:
            continue
        path = os.path.join(MUPDF, "resources", "fonts", forge, fname)
        if not os.path.exists(path):
            # Rows guarded by newer-Unicode #ifs whose font is not shipped.
            print(f"skip (font not shipped): {fname}", file=sys.stderr)
            continue
        sub = "0" if subfont == "NO_SUBFONT" else subfont
        out.append((forge, fname, family, script, lang, sub, attr))
    # De-duplicate identical (file, script, lang, attr) rows, keep order.
    seen, uniq = set(), []
    for r in out:
        key = (r[1], r[3], r[4], r[6])
        if key not in seen:
            seen.add(key)
            uniq.append(r)
    return uniq


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", action="store_true", help="print forge/file paths to copy")
    args = ap.parse_args()
    rs = rows()
    if args.list:
        for f in sorted({(r[0], r[1]) for r in rs}):
            print(f"{f[0]}/{f[1]}")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// GENERATED by scripts/gen_font_map.py from MuPDF font-table.h. Do not edit.\n")
        f.write("// file, family, script, language, subfont, attr\n")
        for forge, fname, family, script, lang, sub, attr in rs:
            f.write(f'{{"{fname}", "{family}", {script}, {lang}, {sub}, {attr}}},\n')
    print(f"wrote {len(rs)} rows to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
